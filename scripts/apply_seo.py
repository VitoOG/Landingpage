#!/usr/bin/env python3
"""Generate SEO metadata, robots.txt and sitemap.xml from seo/site-config.json."""
import argparse,datetime,json,re,shutil,sys,tempfile,os,html
from pathlib import Path
from urllib.parse import urlparse
import xml.etree.ElementTree as ET

START="<!-- BEGIN MANAGED SEO: generated by landingpage-seo-kit -->"
END="<!-- END MANAGED SEO -->"
S="http://www.sitemaps.org/schemas/sitemap/0.9"; X="http://www.w3.org/1999/xhtml"
ET.register_namespace("",S); ET.register_namespace("xhtml",X)

def validate(cfg,root):
 site=cfg["site"]; base=site["base_url"]
 if urlparse(base).scheme!="https" or not base.endswith("/"): raise ValueError("base_url must be trailing-slash HTTPS")
 groups={}
 paths=set(); urls=set()
 for p in site["pages"]:
  q=Path(p["path"])
  if q.is_absolute() or ".." in q.parts: raise ValueError("unsafe page path: "+str(q))
  if p["path"] in paths or p["canonical_url"] in urls: raise ValueError("duplicate path or canonical")
  paths.add(p["path"]); urls.add(p["canonical_url"])
  if not p["canonical_url"].startswith(base) or urlparse(p["canonical_url"]).scheme!="https": raise ValueError("canonical outside base_url")
  if p["language"] not in ("en","ru","lv"): raise ValueError("unsupported language")
  if p["schema_type"] not in ("WebPage","CollectionPage","AboutPage"): raise ValueError("invalid schema_type")
  groups.setdefault(p["translation_group"],[]).append(p)
 for g,items in groups.items():
  langs=[p["language"] for p in items]
  if len(langs)!=len(set(langs)) or "en" not in langs: raise ValueError("invalid translation group: "+g)
 return groups

def alternates(p,groups):
 items=groups[p["translation_group"]]; d={x["language"]:x["canonical_url"] for x in items}
 d["x-default"]=next(x["canonical_url"] for x in items if x["language"]=="en"); return d

def graph(cfg,p,groups):
 base=cfg["site"]["base_url"]; pid=base+"#person"; oid=base+"#organization"; wid=base+"#website"
 person=cfg["person"]; org=cfg["organization"]
 page={"@type":p["schema_type"],"@id":p["canonical_url"]+"#webpage","url":p["canonical_url"],"name":p["title"],"description":p["description"],"inLanguage":p["language"],"isPartOf":{"@id":wid},"about":[{"@id":pid},{"@id":oid}]}
 if p["schema_type"]=="WebPage": page["mainEntity"]={"@id":pid}
 return {"@context":"https://schema.org","@graph":[
 {"@type":"WebSite","@id":wid,"url":base,"name":"Golden Greens Crop","inLanguage":sorted({x["language"] for x in groups[p["translation_group"]]}),"publisher":{"@id":pid}},
 page,
 {"@type":"Person","@id":pid,**person,"url":base,"affiliation":{"@id":oid}},
 {"@type":"Organization","@id":oid,**org,"identifier":{"@type":"PropertyValue","propertyID":"Latvian Enterprise Registration Number","value":org["registration_number"]},"founder":{"@id":pid}}
 ]}

def block(cfg,p,groups):
 e=lambda x:html.escape(str(x),quote=True); alt=alternates(p,groups)
 pair=groups[p["translation_group"]]
 lines=[START,f"<title>{e(p['title'])}</title>",f'<meta name="description" content="{e(p["description"])}">','<meta name="robots" content="index,follow,max-image-preview:large">',f'<link rel="canonical" href="{e(p["canonical_url"])}">','<meta name="author" content="Viktors Simonenko">','<meta property="og:type" content="website">','<meta property="og:site_name" content="Golden Greens Crop">',f'<meta property="og:locale" content="{e(p["locale"])}">',f'<meta property="og:title" content="{e(p["title"])}">',f'<meta property="og:description" content="{e(p["description"])}">',f'<meta property="og:url" content="{e(p["canonical_url"])}">','<meta name="twitter:card" content="summary">']
 lines += [f'<meta property="og:locale:alternate" content="{e(x["locale"])}">' for x in pair if x["locale"]!=p["locale"]]
 lines += [f'<link rel="alternate" hreflang="{e(k)}" href="{e(v)}">' for k,v in alt.items()]
 token=cfg["site"].get("google_site_verification","").strip()
 if token and p is cfg["site"]["pages"][0]:
  if not re.fullmatch(r"[A-Za-z0-9_=-]+",token): raise ValueError("invalid Google verification token")
  lines.append(f'<meta name="google-site-verification" content="{e(token)}">')
 lines += ['<script type="application/ld+json">',json.dumps(graph(cfg,p,groups),ensure_ascii=False,indent=2).replace("</","<\/"),'</script>',END]
 return "\n".join(lines)

def write(path,data,backup,stamp):
 raw=data.encode() if isinstance(data,str) else data
 if path.exists() and path.read_bytes()==raw:return False
 path.parent.mkdir(parents=True,exist_ok=True)
 if path.exists() and backup: shutil.copy2(path,path.with_name(path.name+".pre-seo-"+stamp+".bak"))
 fd,tmp=tempfile.mkstemp(dir=path.parent)
 try:
  with os.fdopen(fd,"wb") as f:f.write(raw);f.flush();os.fsync(f.fileno())
  os.replace(tmp,path)
 finally:
  if os.path.exists(tmp):os.unlink(tmp)
 return True

def main():
 a=argparse.ArgumentParser();a.add_argument("--site-root",default=".");a.add_argument("--config",default="seo/site-config.json");a.add_argument("--no-backup",action="store_true");args=a.parse_args()
 root=Path(args.site_root).resolve()
 try:
  cfg=json.loads(Path(args.config).read_text(encoding="utf-8")); groups=validate(cfg,root); sources=[]
  for p in cfg["site"]["pages"]:
   path=(root/p["path"]).resolve()
   if not path.is_file():raise FileNotFoundError(path)
   try:path.relative_to(root)
   except ValueError:raise ValueError("page path escapes site root")
   src=path.read_text(encoding="utf-8");m=re.search(r"<head\b[^>]*>(.*?)</head\s*>",src,re.I|re.S)
   if not m:raise ValueError("missing head: "+p["path"])
   if not re.search(rf"<html\b[^>]*\blang\s*=\s*['\"]{p['language']}['\"]",src,re.I):raise ValueError("html lang mismatch: "+p["path"])
   sources.append((path,src,p,m))
  stamp=datetime.datetime.now().strftime("%Y%m%d-%H%M%S"); changed=[]
  for path,src,p,m in sources:
   h=m.group(1)
   h=re.sub(re.escape(START)+r".*?"+re.escape(END)+r"\s*","",h,flags=re.S)
   h=re.sub(r"<title\b[^>]*>.*?</title\s*>\s*","",h,flags=re.I|re.S)
   patterns=[r"<meta\b(?=[^>]*\bname\s*=\s*(['\"])(?:description|robots|author|twitter:[^'\"]+)\1)[^>]*>\s*",r"<meta\b(?=[^>]*\bproperty\s*=\s*(['\"])og:[^'\"]+\1)[^>]*>\s*",r"<link\b(?=[^>]*\brel\s*=\s*(['\"])canonical\1)[^>]*>\s*",r"<link\b(?=[^>]*\brel\s*=\s*(['\"])alternate\1)(?=[^>]*\bhreflang\s*=)[^>]*>\s*"]
   for pat in patterns:h=re.sub(pat,"",h,flags=re.I|re.S)
   new=src[:m.start(1)]+h.rstrip()+"\n\n"+block(cfg,p,groups)+"\n"+src[m.end(1):]
   if write(path,new,not args.no_backup,stamp):changed.append(str(path.relative_to(root)))
  robots="# GitHub Pages project site: this path does not control host-level /robots.txt.\nUser-agent: *\nAllow: /\n\nSitemap: "+cfg["site"]["base_url"]+"sitemap.xml\n"
  sm=ET.Element("{"+S+"}urlset")
  for p in cfg["site"]["pages"]:
   u=ET.SubElement(sm,"{"+S+"}url");ET.SubElement(u,"{"+S+"}loc").text=p["canonical_url"]
   for lang,url in alternates(p,groups).items():ET.SubElement(u,"{"+X+"}link",{"rel":"alternate","hreflang":lang,"href":url})
  ET.indent(sm,space="  "); sitemap=ET.tostring(sm,encoding="utf-8",xml_declaration=True)+b"\n"
  for path,data in ((root/"robots.txt",robots),(root/"sitemap.xml",sitemap)):
   if write(path,data,not args.no_backup,stamp):changed.append(path.name)
  print("Updated: "+", ".join(changed) if changed else "No changes required.")
  return 0
 except Exception as e:print("ERROR:",e,file=sys.stderr);return 2
if __name__=="__main__":raise SystemExit(main())
